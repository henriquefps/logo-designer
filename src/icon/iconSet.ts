import { cleanGlyph, inkBox, report, shapeOf, type IconReport, type Rasterize } from './measure';
import {
  ADAPTIVE_XML,
  ANDROID_DENSITIES,
  backgroundXml,
  tileOf,
  IOS_APPICON,
  IOS_CONTENTS_JSON,
  ICON_COMPOSER_GLYPH,
  iconComposerGlyphSvg,
  iconComposerJson,
  iosDarkSvg,
  iosTintedSvg,
  darkTile,
  encodeIco,
  encodeOpaquePng,
  faviconSvg,
  layerSvg,
  legacyLauncherSvg,
  legacyRoundSvg,
  lightTile,
  sheetSvg,
  sheetTiles,
  splashDrawable,
  squareSvg,
  SHEET,
  type Deflate,
  type IconSources,
} from './outputs';
import { IOS_TINTED_BG, SMALL_FILL, type IconShape, type IconShapeArg } from './rules';

export interface IconRenderer {
  /** Raw pixels (RGBA) of an SVG rendered at px × px (used to measure and for the opaque iOS PNG). */
  rasterize: Rasterize;
  /** PNG bytes of an SVG rendered at size × size. */
  png: (svg: string, size: number) => Promise<Uint8Array>;
  /** PNG bytes of an SVG rendered at its own width × height (the review sheet). */
  pngAt: (svg: string, width: number, height: number) => Promise<Uint8Array>;
  deflate: Deflate;
}

export interface IconFile {
  path: string;
  data: Uint8Array | string;
}

export interface IconSetInput {
  /** Glyph fragment in the 128 space with currentColor (glyph.svg). */
  glyph: string;
  /** Simplified favicon glyph (glyph-small.svg). */
  small?: string;
  shape?: IconShapeArg;
  /** Extra files copied as-is (the .designer.json project, …). */
  extra?: IconFile[];
  /** Tile colour `#rrggbb` (default BRAND `#2063b0`; older hfps repos: olive `#5b7a3a`). */
  tile?: string;
}

export interface IconSetResult {
  files: IconFile[];
  report: IconReport;
  smallShape?: IconShape;
  /** Lines the script prints with a leading `!` (e.g. no splash drawable). */
  notes: string[];
}

/** Measures the glyph(s) and returns the sources every builder takes. */
export async function prepareSources(input: Pick<IconSetInput, 'glyph' | 'small' | 'shape' | 'tile'>, rasterize: Rasterize) {
  const src = cleanGlyph(input.glyph);
  const box = await inkBox(src, rasterize);
  if (!box) throw new Error('The glyph has no visible ink.');
  const smallSrc = input.small ? cleanGlyph(input.small) : undefined;
  const smallBox = smallSrc ? await inkBox(smallSrc, rasterize) : undefined;
  if (smallSrc && !smallBox) throw new Error('The small glyph has no visible ink.');
  const shape = shapeOf(box, input.shape ?? 'auto');
  const sources: IconSources = { glyph: { src, box }, shape, ...(input.tile ? { tile: input.tile } : {}), ...(smallSrc && smallBox ? { small: { src: smallSrc, box: smallBox } } : {}) };
  const smallShape = smallBox ? shapeOf(smallBox, input.shape ?? 'auto') : undefined;
  return { sources, report: report(box, input.shape ?? 'auto'), smallShape };
}

function readme(r: IconReport, smallShape: IconShape | undefined, hasSmall: boolean): string {
  return `hfps app icon set, generated by Designer (designer.hfps.dev) with the same rules and
numbers as build-icons.mjs from the hfps-repo-assets skill.

Measured:
${r.lines.join('\n')}${hasSmall ? `\nfavicon glyph (${smallShape}) at ${SMALL_FILL * 100}%` : ''}

Where each folder goes:
  glyph.svg             the glyph (128 space, currentColor): keep it as scripts/glyph.svg so
                        build-icons.mjs can rebuild everything from it
  glyph-small.svg       simplified favicon glyph (--small), when there is one
  *.designer.json       the Designer project: open it in Designer to edit the icon later
  docs-img/             docs/img in the repo: icon.svg, icon-light.svg, icon.png (README, CHANGELOG)
  site/                 the web root: favicon.ico, icon.svg, apple-touch-icon.png, icon-192.png,
                        icon-512.png, icon-maskable-512.png. In <head>:
                          <link rel="icon" href="favicon.ico" sizes="48x48">
                          <link rel="icon" href="icon.svg" type="image/svg+xml">
                          <link rel="apple-touch-icon" href="apple-touch-icon.png">
                        In a PWA manifest list icon-maskable-512.png with "purpose": "maskable".
  android/res/          merge into android/app/src/main/res: mipmap-*/ic_launcher{,_round,
                        _foreground,_monochrome}.png, mipmap-anydpi-v26/*.xml,
                        values/ic_launcher_background.xml (an existing file keeps its other colours),
                        drawable/ic_splash.xml. Delete an older vector
                        drawable/ic_launcher_foreground.xml so the new mipmaps win.
                        Android 13+ themed icons use <monochrome> (ic_launcher_monochrome: the
                        glyph alone); the launcher tints it with the wallpaper colours.
                        Splash (Android 12+): point the splash theme at @drawable/ic_splash
                        (windowSplashScreenAnimatedIcon). It is the glyph as a VectorDrawable, so it
                        stays sharp where the PNG foreground would be upscaled and blurred.
  ios/AppIcon.appiconset/
                        goes into the app's Assets.xcassets (iOS 18+ Light / Dark / Tinted):
                          AppIcon-1024.png         Light (Any): opaque, no alpha, brand blue tile (or --tile)
                          AppIcon-1024-dark.png    Dark: glyph in light blue on transparency; iOS
                                                   draws its own dark background behind it
                          AppIcon-1024-tinted.png  Tinted: opaque grayscale, white glyph on black;
                                                   iOS recolours it with the user's tint
                          Contents.json            the three images with their "luminosity" appearances
  ios/AppIcon.icon/     iOS 26 Icon Composer file (Liquid Glass, layered): icon.json + Assets/glyph.svg.
                        Drag it into the Xcode project (Xcode 26+) and set the target's App Icon
                        name to "AppIcon"; it then replaces the asset catalog icon, and Xcode
                        generates the older-iOS images from it. Open it in Icon Composer to check
                        Default / Dark / Clear / Tinted. Keep the .appiconset for Xcode < 26.
  review-sheet.png      row 1: masks at 128 px, the pink 0.63 T reference circle on the first one; row 2:
                        launcher sizes; row 3: favicons on dark and on white. Always look at it.
`;
}

type Add = (path: string, data: Uint8Array | string) => void;

/**
 * iOS 18+ AppIcon.appiconset: Light = one opaque 1024 PNG flattened on the brand blue (no alpha);
 * Dark = the glyph in IOS_DARK_GLYPH on transparency; Tinted = opaque grayscale (white glyph on black).
 */
export async function addIosAppIconSet(sources: IconSources, r: IconRenderer, add: Add): Promise<void> {
  const dir = 'ios/AppIcon.appiconset';
  const light = await r.rasterize(squareSvg(sources), 1024);
  add(`${dir}/${IOS_APPICON.light}`, await encodeOpaquePng(light.data, light.width, light.height, tileOf(sources), r.deflate));
  add(`${dir}/${IOS_APPICON.dark}`, await r.png(iosDarkSvg(sources), 1024));
  const tinted = await r.rasterize(iosTintedSvg(sources), 1024);
  add(`${dir}/${IOS_APPICON.tinted}`, await encodeOpaquePng(tinted.data, tinted.width, tinted.height, IOS_TINTED_BG, r.deflate));
  add(`${dir}/Contents.json`, IOS_CONTENTS_JSON);
}

/** iOS 26 Icon Composer file: AppIcon.icon/icon.json + Assets/glyph.svg (background is a fill, not a layer). */
export function addIconComposerFile(sources: IconSources, add: Add): void {
  add('ios/AppIcon.icon/icon.json', iconComposerJson(tileOf(sources)));
  add(`ios/AppIcon.icon/Assets/${ICON_COMPOSER_GLYPH}`, iconComposerGlyphSvg(sources));
}

/** Builds every file of the set (paths relative to the ZIP root). */
export async function buildIconSet(input: IconSetInput, r: IconRenderer): Promise<IconSetResult> {
  const { sources, report: rep, smallShape } = await prepareSources(input, r.rasterize);
  const files: IconFile[] = [];
  const notes: string[] = [];
  const add = (path: string, data: Uint8Array | string) => files.push({ path, data });

  add('glyph.svg', input.glyph);
  if (input.small) add('glyph-small.svg', input.small);

  // docs/img
  const dark = darkTile(sources);
  add('docs-img/icon.svg', dark);
  add('docs-img/icon-light.svg', lightTile(sources));
  add('docs-img/icon.png', await r.png(dark, 1024));

  // site
  const fav = faviconSvg(sources);
  add('site/icon.svg', dark);
  const sizes = [16, 32, 48];
  add('site/favicon.ico', encodeIco(await Promise.all(sizes.map((s) => r.png(fav, s))), sizes));
  add('site/apple-touch-icon.png', await r.png(squareSvg(sources), 180));
  add('site/icon-192.png', await r.png(dark, 192));
  add('site/icon-512.png', await r.png(dark, 512));
  add('site/icon-maskable-512.png', await r.png(squareSvg(sources), 512));

  // android
  const fg = layerSvg(sources, '#fff'),
    mono = layerSvg(sources, '#000');
  const legacy = legacyLauncherSvg(sources),
    round = legacyRoundSvg(sources);
  for (const [d, k] of Object.entries(ANDROID_DENSITIES)) {
    const dir = `android/res/mipmap-${d}`;
    add(`${dir}/ic_launcher_foreground.png`, await r.png(fg, Math.round(108 * k)));
    add(`${dir}/ic_launcher_monochrome.png`, await r.png(mono, Math.round(108 * k)));
    add(`${dir}/ic_launcher.png`, await r.png(legacy, Math.round(48 * k)));
    add(`${dir}/ic_launcher_round.png`, await r.png(round, Math.round(48 * k)));
  }
  add('android/res/mipmap-anydpi-v26/ic_launcher.xml', ADAPTIVE_XML);
  add('android/res/mipmap-anydpi-v26/ic_launcher_round.xml', ADAPTIVE_XML);
  add('android/res/values/ic_launcher_background.xml', backgroundXml(tileOf(sources)));
  const splash = splashDrawable(sources);
  if (splash.xml) add('android/res/drawable/ic_splash.xml', splash.xml);
  else notes.push(`! android splash: no ic_splash.xml (${splash.error}); export the glyph from the Designer (to-svg --glyph) so it is plain paths`);

  // iOS
  await addIosAppIconSet(sources, r, add);
  addIconComposerFile(sources, add);

  // review sheet
  const tiles = await Promise.all(sheetTiles(sources).map(async (t) => ({ ...t, png: await r.png(t.svg, t.size) })));
  add('review-sheet.png', await r.pngAt(sheetSvg(tiles), SHEET.width, SHEET.height));

  add('README.txt', readme(rep, smallShape, !!input.small));
  for (const f of input.extra ?? []) add(f.path, f.data);
  return { files, report: rep, smallShape, notes };
}
